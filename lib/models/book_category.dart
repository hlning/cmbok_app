  /// 将抓到的英文分类名翻译为中文显示名。
  ///
  /// [context] 为主分类英文名（子分类翻译时传入，用于 [_zhNamesOverride] 消歧）。
  /// 末尾的 `(数字)` 计数保留（如 `Architecture (22751)` -> `建筑 (22751)`）；
  /// 译名表未收录的返回原文。
  static String translate(String raw, {String? context}) {
    if (raw.isEmpty) return raw;
    final m = RegExp(r'\s*\((\d[\d,]*)\)\s*$').firstMatch(raw);
    if (m != null) {
      final base = raw.substring(0, m.start).trim();
      final suffix = raw.substring(m.start);
      final zh = _lookup(base, context);
      return zh == null ? raw : '$zh$suffix';
    }
    return _lookup(raw, context) ?? raw;
  }

  static String? _lookup(String base, String? context) {
    if (context != null) {
      final ov = _zhNamesOverride['$context|$base'];
      if (ov != null) return ov;
    }
    return _zhNames[base];
  }
