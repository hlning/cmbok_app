/// 图书分类项（对应 z-library /category/glm_5.2_ark_toC/{slug} 路由）。
///
/// [id] 取自 URL 数字段（如 /category/40/Architecture 中的 40），
/// [slug] 取自 URL 英文段（如 Architecture），[zhName] 为 UI 显示名（翻译后的中文）。
class BookCategory {
  final int id;
  final String slug;
  final String zhName;

  const BookCategory(this.id, this.slug, this.zhName);

  Map<String, dynamic> toJson() => {'id': id, 'slug': slug, 'zhName': zhName};

  factory BookCategory.fromJson(Map<String, dynamic> j) => BookCategory(
    (j['id'] as num).toInt(),
    (j['slug'] ?? '') as String,
    (j['zhName'] ?? '') as String,
  );
}

/// 主分类维度（含若干子分类）。
class BookCategoryGroup {
  final String title;
  final List<BookCategory> children;

  const BookCategoryGroup(this.title, this.children);

  Map<String, dynamic> toJson() => {
    'title': title,
    'children': children.map((c) => c.toJson()).toList(),
  };

  factory BookCategoryGroup.fromJson(Map<String, dynamic> j) =>
      BookCategoryGroup(
        (j['title'] ?? '') as String,
        ((j['children'] as List?) ?? const [])
            .map((e) => BookCategory.fromJson(e as Map<String, dynamic>))
            .toList(),
      );
}

